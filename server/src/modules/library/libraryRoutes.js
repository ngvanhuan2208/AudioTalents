const express = require('express');
const {authMiddleware} = require('../../middleware/auth');
const controller = require('./libraryController');
const {asyncHandler} = require('../../middleware/asyncHandler');
const router = express.Router();
router.use(authMiddleware);
router.get('/', asyncHandler(controller.list));
router.post('/:storyId', asyncHandler(controller.addStory));
router.delete('/:storyId', asyncHandler(controller.removeStory));
router.post('/favorites/:storyId', asyncHandler(controller.toggleFavorite));
router.delete('/favorites/:storyId', asyncHandler(controller.toggleFavorite));
router.get('/favorites', asyncHandler(controller.favorites));
router.post('/follow/:storyId', asyncHandler(controller.toggleFollow));
router.delete('/follow/:storyId', asyncHandler(controller.toggleFollow));
router.get('/history', asyncHandler(controller.history));
router.delete('/history/:id', asyncHandler(controller.removeHistory));
router.get('/progress', asyncHandler(controller.progress));
router.post('/progress', asyncHandler(controller.saveProgress));
module.exports = router;
